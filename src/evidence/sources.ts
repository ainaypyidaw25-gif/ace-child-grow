// Evidence Base — the verified reference registry.
//
// HOW THIS FILE IS MAINTAINED
// ---------------------------
// Every record below was produced by opening the URL in `url` and reading the
// metadata off that page. `verifiedNote` records what was actually seen. No
// field here may be filled in from memory, inference, or pattern-matching:
//   * a year that is not printed on the page  -> year: null
//   * a DOI that was not printed on the page  -> doi: null
//   * an ISBN that was not printed on the page -> isbn: null
// A record missing a printed year is forced to 'evidence_required' by
// resolveReviewStatus() in ./types — that is the intended behaviour, not a bug.
//
// No record here is 'approved'. Approval requires a named qualified reviewer,
// which is a human act performed in the admin Evidence Library. Ordinary
// reference approval is education-scoped; clinical scope remains a separate
// specialist-risk decision and is never inferred from parent visibility.

import type { EvidenceSource } from './types';

/** The date this registry was verified against the publisher pages. */
export const REGISTRY_VERIFIED_ON = '2026-07-24';

type Required_ = Pick<
  EvidenceSource,
  'id' | 'org' | 'orgKey' | 'title' | 'url' | 'evidenceLevel' | 'verifiedNote'
>;

/**
 * Builds a source record with the registry defaults. Defaults are deliberately
 * the *cautious* values: unknown identifiers are null, and nothing is approved.
 */
function s(input: Required_ & Partial<EvidenceSource>): EvidenceSource {
  return {
    authors: null,
    year: null,
    edition: null,
    country: 'International',
    language: 'en',
    doi: null,
    isbn: null,
    pmid: null,
    reviewStatus: 'awaiting_review',
    reviewer: null,
    reviewDate: null,
    nextReviewDate: null,
    keywords: [],
    topics: [],
    ageMonthsMin: null,
    ageMonthsMax: null,
    verifiedOn: REGISTRY_VERIFIED_ON,
    ...input,
  };
}

